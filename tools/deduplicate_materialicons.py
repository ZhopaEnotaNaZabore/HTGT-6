"""Deduplicate exact RGBA + metadata within each Minecraft texture atlas (requires Pillow)."""
from pathlib import Path
from collections import defaultdict
import argparse
import hashlib
import json
import zipfile
from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    assets = root / 'src/main/resources/assets/htgt6'
    manifest = assets / 'materialicon-aliases.properties'
    previous = {}
    if manifest.exists():
        for line in manifest.read_text(encoding='ascii').splitlines():
            if line and not line.startswith('#'):
                key, value = line.split('=', 1)
                previous[key] = value
    aliases, removals = {}, []
    before = after = count = 0
    for kind in ('items', 'blocks'):
        directory = assets / 'textures' / kind / 'materialicons'
        groups = defaultdict(list)
        signatures = {}
        for path in sorted(directory.rglob('*.png')):
            image = Image.open(path).convert('RGBA')
            meta = Path(str(path) + '.mcmeta')
            metadata = meta.read_bytes() if meta.exists() else b''
            signature = (image.size, hashlib.sha256(image.tobytes()).digest(), metadata)
            name = path.relative_to(directory).as_posix()[:-4]
            signatures[name] = signature
            groups[signature].append(path)
            before += path.stat().st_size + len(metadata)
            count += 1
        targets = {}
        for paths in groups.values():
            canonical = min(paths, key=lambda p: (p.stat().st_size, p.as_posix()))
            target = canonical.relative_to(directory).as_posix()[:-4]
            after += canonical.stat().st_size
            meta = Path(str(canonical) + '.mcmeta')
            if meta.exists():
                after += meta.stat().st_size
            for path in paths:
                name = path.relative_to(directory).as_posix()[:-4]
                targets[name] = target
                if path != canonical:
                    removals.append(path)
                    sidecar = Path(str(path) + '.mcmeta')
                    if sidecar.exists():
                        removals.append(sidecar)
        for key, target in previous.items():
            if key.startswith(kind + '/'):
                name = key[len(kind) + 1:]
                if name not in targets:
                    if target not in targets:
                        raise ValueError('Missing alias target: ' + key)
                    targets[name] = targets[target]
        for name, target in targets.items():
            assert target in signatures
            if name in signatures:
                assert signatures[name] == signatures[target]
            if name != target:
                aliases[kind + '/' + name] = target
    text = '# Generated by tools/deduplicate_materialicons.py; paths are atlas-relative.\n'
    text += ''.join(key + '=' + aliases[key] + '\n' for key in sorted(aliases))
    # Validate every deletion target before writing or removing anything.
    for path in removals:
        path.resolve().relative_to((assets / 'textures').resolve())
    if removals:
        backup = root / 'build/materialicons-before-dedup.zip'
        backup.parent.mkdir(parents=True, exist_ok=True)
        # Keep the first backup; later regeneration must not overwrite it.
        if not backup.exists():
            with zipfile.ZipFile(backup, 'w', zipfile.ZIP_DEFLATED) as archive:
                for path in removals:
                    archive.write(path, path.relative_to(root).as_posix())
    manifest.write_text(text, encoding='ascii')
    for path in removals:
        path.unlink()
    print(json.dumps(dict(png_before=count, png_removed=sum(p.suffix == '.png' for p in removals),
                          bytes_before=before, bytes_after=after, alias_bytes=manifest.stat().st_size,
                          aliases=len(aliases)), indent=2))


if __name__ == '__main__':
    main()
