    /**
     * Converts the modern blast-resistance value to the 1.7.10 registration argument.
     * Legacy Block#setResistance multiplies by three and getExplosionResistance divides by five.
     */
    public static float legacyResistance(float modernResistance) {
        return modernResistance * 5.0F / 3.0F;
    }

