package com.mod.htgt6.common.handler.recipes;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

import gregapi.data.OP;
import gregapi.data.RM;
import gregapi.oredict.OreDictItemData;
import gregapi.recipes.Recipe;
import gregapi.util.OM;
import net.minecraft.item.Item;
import net.minecraft.item.ItemStack;
import net.minecraftforge.oredict.OreDictionary;

/** Collects both stored and input-generated GT6 crushing recipes. */
public final class GT6CrusherRecipeCollector {
    private GT6CrusherRecipeCollector() { }

    /** Snapshot including GT6's input-generated crushed-ore Shredder stages. */
    public static List<Recipe> recipesFor(Recipe.RecipeMap source) {
        return java.util.Collections.unmodifiableList(new ArrayList<Recipe>(collect(source).recipes));
    }

    static Snapshot collect(Recipe.RecipeMap source) {
        int before = source.mRecipeList.size();
        List<Recipe> recipes = new ArrayList<Recipe>(source.getNEIAllRecipes());
        Snapshot result = new Snapshot(recipes,
                Math.max(0, source.mRecipeList.size() - before));

        // 6.15.08 moved the three ore-processing stages into
        // RecipeMapShredder#getRecipeFor. getNEIAllRecipes() cannot enumerate
        // recipes generated by that input-driven method, so ask the map for
        // every registered whole crushed-ore stack explicitly.
        if (source == RM.Shredder) {
            Set<String> inputs = new HashSet<String>();
            for (Recipe recipe : recipes) addInputKey(inputs, recipe);

            for (String oreName : OreDictionary.getOreNames()) {
                if (oreName == null || !oreName.startsWith("crushed")) continue;
                for (ItemStack registered : OreDictionary.getOres(oreName)) {
                    OreDictItemData data = association(registered);
                    if (!isCrushedStage(data)) continue;

                    ItemStack input = registered.copy();
                    input.stackSize = 1;
                    String key = stackKey(input);
                    if (!inputs.add(key)) continue;

                    // The runtime findRecipe path is disabled until ServerStarted.
                    // loadComplete (and client NEI) must use GT6's public usage
                    // enumeration, which invokes getRecipeFor without that gate.
                    for (Recipe generated : recipesForInput(source, input)) {
                        if (generated == null || !generated.mEnabled || generated.mFakeRecipe) continue;
                        recipes.add(generated);
                        result.dynamic++;
                    }
                }
            }
        }
        return result;
    }

    static List<Recipe> recipesForInput(Recipe.RecipeMap source, ItemStack input) {
        return source.getNEIUsages(input);
    }

    private static OreDictItemData association(ItemStack stack) {
        // Match RecipeMapShredder's own input/material lookup.
        OreDictItemData data = OM.anydata(stack);
        return data != null && data.hasValidPrefixMaterialData()
                && data.mPrefix != null && data.mMaterial != null
                && data.mMaterial.mMaterial != null ? data : null;
    }

    private static boolean isCrushedStage(OreDictItemData data) {
        return data != null && (data.mPrefix == OP.crushed
                || data.mPrefix == OP.crushedPurified
                || data.mPrefix == OP.crushedCentrifuged);
    }

    private static void addInputKey(Set<String> inputs, Recipe recipe) {
        if (recipe != null && recipe.mInputs != null && recipe.mInputs.length == 1
                && recipe.mInputs[0] != null && recipe.mInputs[0].getItem() != null) {
            inputs.add(stackKey(recipe.mInputs[0]));
        }
    }

    private static String stackKey(ItemStack stack) {
        return Item.getIdFromItem(stack.getItem()) + ":" + stack.getItemDamage() + ":"
                + (stack.hasTagCompound() ? stack.getTagCompound().toString() : "");
    }

    static final class Snapshot {
        final List<Recipe> recipes;
        final int materialized;
        int dynamic;

        Snapshot(List<Recipe> recipes, int materialized) {
            this.recipes = recipes;
            this.materialized = materialized;
        }
    }
}
